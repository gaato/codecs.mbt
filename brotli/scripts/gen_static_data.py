#!/usr/bin/env python3
"""Generates src/static_data.mbt: the RFC 7932 static dictionary, the 121
word transforms and the literal context lookup tables.

Sources, both pinned:
- the dictionary: google/brotli's c/common/dictionary.bin (MIT, see
  LICENSE-dictionary), byte-identical to RFC 7932 Appendix A;
- the transforms (Appendix B) and Lut0/Lut1/Lut2 (section 7.1): the RFC text.

src/static_data_test.mbt checks the result against the check values the RFC
and google publish, so a regenerated file cannot drift silently.

Usage: scripts/gen_static_data.py [DICTIONARY_BIN RFC7932_TXT]
Without arguments both are downloaded from the pinned URLs below.
"""

import ast
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

BROTLI_COMMIT = "86ee1f65f62d6272345dee751d49e7d1f01c2b11"
DICTIONARY_URL = (
    f"https://raw.githubusercontent.com/google/brotli/{BROTLI_COMMIT}"
    "/c/common/dictionary.bin"
)
RFC_URL = "https://www.rfc-editor.org/rfc/rfc7932.txt"
# Dictionary bytes per source line.
CHUNK = 512

# RFC 7932 Appendix B names, in the order of the decoder's transform types.
TRANSFORM_TYPES = (
    ["Identity"]
    + [f"OmitLast{i}" for i in range(1, 10)]
    + ["FermentFirst", "FermentAll"]
    + [f"OmitFirst{i}" for i in range(1, 10)]
)


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url) as response:
        return response.read()


def bytes_literal(data: bytes) -> str:
    out = []
    for b in data:
        if 0x20 <= b < 0x7F and b not in (0x22, 0x5C):
            out.append(chr(b))
        else:
            out.append(f"\\x{b:02x}")
    return 'b"' + "".join(out) + '"'


def lut(rfc: str, name: str) -> list[int]:
    start = rfc.index(f"      {name} :=")
    numbers: list[int] = []
    for line in rfc[start:].splitlines()[1:]:
        if re.fullmatch(r"\s*(\d+,\s*)*\d+,?\s*", line):
            numbers += [int(n) for n in re.findall(r"\d+", line)]
            if len(numbers) == 256:
                return numbers
        elif numbers and line.strip() and not line.startswith(("RFC", "Alakuijala")):
            break
    raise SystemExit(f"{name}: found {len(numbers)} values, expected 256")


def transforms(rfc: str) -> list[tuple[bytes, int, bytes]]:
    body = rfc[rfc.index("Appendix B.  List of Word Transformations") :]
    row = re.compile(r'^\s+(\d+)\s+("(?:[^"\\]|\\.)*")\s+(\w+)\s+("(?:[^"\\]|\\.)*")\s*$')
    found = []
    for line in body.splitlines():
        m = row.match(line)
        if m:
            index = int(m.group(1))
            if index != len(found):
                raise SystemExit(f"transform {index} out of order")
            prefix = ast.literal_eval("b" + m.group(2))
            suffix = ast.literal_eval("b" + m.group(4))
            found.append((prefix, TRANSFORM_TYPES.index(m.group(3)), suffix))
    if len(found) != 121:
        raise SystemExit(f"found {len(found)} transforms, expected 121")
    return found


def main() -> None:
    if len(sys.argv) == 3:
        dictionary = Path(sys.argv[1]).read_bytes()
        rfc = Path(sys.argv[2]).read_text()
    else:
        dictionary = fetch(DICTIONARY_URL)
        rfc = fetch(RFC_URL).decode()
    if len(dictionary) != 122784:
        raise SystemExit(f"dictionary is {len(dictionary)} bytes, expected 122784")
    rows = transforms(rfc)
    out = [
        "// Generated by scripts/gen_static_data.py, DON'T EDIT IT.",
        "// The dictionary is google/brotli's c/common/dictionary.bin at",
        f"// {BROTLI_COMMIT} (MIT, see LICENSE-dictionary); the",
        "// transforms and context tables are transcribed from RFC 7932.",
        "",
    ]
    for name in ("Lut0", "Lut1", "Lut2"):
        values = ", ".join(str(v) for v in lut(rfc, name))
        out += [
            "///|",
            f"/// RFC 7932 section 7.1, `{name}`.",
            f"let {name.lower()} : FixedArray[Byte] = [{values}]",
            "",
        ]
    prefixes = ", ".join(bytes_literal(p) for p, _, _ in rows)
    types = ", ".join(str(t) for _, t, _ in rows)
    suffixes = ", ".join(bytes_literal(s) for _, _, s in rows)
    out += [
        "///|",
        "/// RFC 7932 Appendix B: the prefix of each transform.",
        f"let transform_prefixes : FixedArray[Bytes] = [{prefixes}]",
        "",
        "///|",
        "/// RFC 7932 Appendix B: the elementary transform of each transform:",
        "/// 0 Identity, 1-9 OmitLast1-9, 10 FermentFirst, 11 FermentAll,",
        "/// 12-20 OmitFirst1-9.",
        f"let transform_types : FixedArray[Byte] = [{types}]",
        "",
        "///|",
        "/// RFC 7932 Appendix B: the suffix of each transform.",
        f"let transform_suffixes : FixedArray[Bytes] = [{suffixes}]",
        "",
        "///|",
        "/// RFC 7932 Appendix A: the static dictionary, 122,784 bytes, in",
        "/// chunks that keep each source line short.",
        "let dictionary : Bytes = {",
        "  let chunks : FixedArray[Bytes] = [",
    ]
    out += [
        f"    {bytes_literal(dictionary[i : i + CHUNK])},"
        for i in range(0, len(dictionary), CHUNK)
    ]
    out += [
        "  ]",
        f"  let buffer = Buffer(size_hint={len(dictionary)})",
        "  for chunk in chunks {",
        "    buffer.write_bytes(chunk)",
        "  }",
        "  buffer.to_bytes()",
        "}",
        "",
    ]
    target = Path(__file__).resolve().parent.parent / "src" / "static_data.mbt"
    target.write_text("\n".join(out))
    # Leave the file as `moon fmt` would, so the gates' fmt check passes.
    subprocess.run(["moon", "fmt"], cwd=target.parent.parent, check=True)
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
