#!/usr/bin/env python3
"""Generates bench/src/data_test.mbt: the inputs of the benchmarks.

A deterministic text of 512 KiB (words drawn by a seeded generator, with
punctuation and line breaks) and a deterministic binary-like stream, each
compressed by the reference implementations: `zstd -3` (the CLI) and the
`brotli` Python module at quality 9 and window 22. The benchmarks decode
these, so the decoders meet what common encoders produce.

Usage: scripts/gen_bench_data.py [--check]
"""

import base64
import random
import subprocess
import sys
from pathlib import Path

import brotli

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "bench" / "src" / "data_test.mbt"
WORDS = ("the of and to in is that for it as with was on be by this are from at "
         "or an have not which but stream window block frame decoder encoder "
         "literal sequence offset match length table code symbol state bits "
         "compression data input output buffer memory limit header checksum").split()


def text(n):
    rng = random.Random(8878)
    out = []
    size = 0
    while size < n:
        w = rng.choice(WORDS)
        if rng.random() < 0.08:
            w = w.capitalize()
        sep = rng.choices([" ", ", ", ". ", "\n"], [80, 8, 8, 4])[0]
        out.append(w + sep)
        size += len(w) + len(sep)
    return "".join(out).encode()[:n]


def binary(n):
    rng = random.Random(7932)
    out = bytearray()
    while len(out) < n:
        # Records: a small header, a counter, and noise of varying length.
        out += bytes([0x7f, 0x45, rng.randrange(4), 0])
        out += len(out).to_bytes(4, "little")
        out += bytes(rng.randrange(256) for _ in range(rng.randrange(4, 40)))
    return bytes(out[:n])


def zstd3(data):
    return subprocess.run(["zstd", "-3", "-q", "-c", "--no-progress"], input=data,
                          capture_output=True, check=True).stdout


def render():
    inputs = {"text": text(1 << 19), "binary": binary(1 << 17)}
    lines = ["// Generated by scripts/gen_bench_data.py, DON'T EDIT IT.", ""]
    for name, raw in inputs.items():
        for fmt, packed in (("zstd", zstd3(raw)), ("brotli", brotli.compress(raw, quality=9, lgwin=22))):
            b64 = base64.b64encode(packed).decode()
            lines += ["///|", f"/// {name} ({len(raw)} bytes) as {fmt} produces it ({len(packed)} bytes).",
                      f"let {fmt}_{name} : String =", "  #|" + b64[:76]]
            lines += ["  #|" + b64[i:i + 76] for i in range(76, len(b64), 76)]
            lines += [""]
        lines += ["///|", f"let {name}_size : Int = {len(raw)}", ""]
    return "\n".join(lines)


def main():
    out = render()
    if "--check" in sys.argv[1:]:
        if not TARGET.exists() or TARGET.read_text() != out:
            sys.exit("bench/src/data_test.mbt is stale: run scripts/gen_bench_data.py")
        return
    TARGET.write_text(out)
    print(f"{TARGET.relative_to(ROOT)}: {len(out)} bytes")


if __name__ == "__main__":
    main()
