#!/usr/bin/env python3
"""Generates conformance/src/<format>_vectors_test.mbt from each format's vectors.

The conformance suite runs every format through the shared harness: splits,
truncation, trailing bytes, reset and fuzzing, each over many runs per
vector. It takes the smaller vectors of each module's vectors_wbtest.mbt
(already generated from reference implementations and upstream test data),
so that the suite covers every kind of stream without the run time of the
large ones.

Usage: scripts/gen_conformance_vectors.py [--check]
--check regenerates into memory and fails if a generated file differs.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FORMATS = ["zstd", "brotli"]
MAX_SIZE = 1 << 16          # decoded bytes
MAX_COMPRESSED = 6000       # base64 characters
MAX_VECTORS = 48

ENTRY = re.compile(
    r"\{\s*name: \"(?P<name>[^\"]*)\",\s*compressed: \(\s*(?P<lines>(?:#\|[^\n]*\n\s*)*)\),"
    r"\s*size: (?P<size>\d+),\s*sha256: \"(?P<sha>[0-9a-f]{64})\","
    r"(?:\s*window_bits: (?P<wbits>\d+),)?\s*\}",
)


def vectors(fmt):
    text = (ROOT / fmt / "src" / "vectors_wbtest.mbt").read_text()
    body = text[text.index("let vectors"):]
    body = body[: body.index("\n]\n")]
    for m in ENTRY.finditer(body):
        b64 = "".join(line.strip()[2:] for line in m.group("lines").strip().splitlines())
        yield m.group("name"), b64, int(m.group("size")), m.group("sha"), m.group("wbits")


def render(fmt):
    chosen = [v for v in vectors(fmt) if v[2] <= MAX_SIZE and len(v[1]) <= MAX_COMPRESSED]
    chosen = chosen[:MAX_VECTORS]
    out = [
        "// Generated by scripts/gen_conformance_vectors.py from",
        f"// {fmt}/src/vectors_wbtest.mbt, DON'T EDIT IT.",
        "",
        "///|",
        f"let {fmt}_vectors : Array[Vector] = [",
    ]
    for name, b64, size, sha, wbits in chosen:
        out.append("  {")
        out.append(f'    name: "{name}",')
        out.append("    compressed: (")
        for i in range(0, max(len(b64), 1), 76):
            out.append(f"      #|{b64[i:i + 76]}")
        out.append("    ),")
        out.append(f"    size: {size},")
        out.append(f'    sha256: "{sha}",')
        out.append(f"    window_bits: {wbits or 24},")
        out.append("  },")
    out.append("]")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for fmt in FORMATS:
        target = ROOT / "conformance" / "src" / f"{fmt}_vectors_test.mbt"
        text = render(fmt)
        if check:
            if not target.exists() or target.read_text() != text:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
            print(f"{target.relative_to(ROOT)}: {text.count('    name: ')} vectors")
    if stale:
        print("stale: " + ", ".join(stale) + " (run scripts/gen_conformance_vectors.py)", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
